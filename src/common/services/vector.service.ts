import { EmbeddingService } from '@/common/services/embedding.service';
import { SupabaseService } from '@/common/services/supabase.service';
import { DatabaseService } from '@/database/database.service';
import { documentChunk, DocumentChunkMetadata } from '@/database/schemas/chunk.schema';
import { DocumentMetadata, libraryItem, LibraryItemMetadata, LibraryItemType } from '@/database/schemas/library.schema';
import { PDFLoader } from '@langchain/community/document_loaders/fs/pdf';
import { Document } from '@langchain/core/documents';
import { RecursiveCharacterTextSplitter } from '@langchain/textsplitters';
import { HttpService } from '@nestjs/axios';
import { BadRequestException, Injectable, Logger, NotFoundException } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { and, cosineDistance, eq, inArray } from 'drizzle-orm';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { firstValueFrom } from 'rxjs';

export type RetrievedChunk = {
    itemUid: string;
    itemName: string;
    content: string;
    pageNumber: number | null;
    chunkIndex: number;
    score: number;
};

export type SearchOptions = {
    limit?: number;
    minScore?: number;
    itemUids?: string[];
};

const INSERT_BATCH_SIZE = 100;

@Injectable()
export class VectorService {
    private readonly logger = new Logger(VectorService.name);
    private readonly textSplitter: RecursiveCharacterTextSplitter;

    constructor(
        private readonly databaseService: DatabaseService,
        private readonly embeddingService: EmbeddingService,
        private readonly supabaseService: SupabaseService,
        private readonly httpService: HttpService,
        private readonly configService: ConfigService,
    ) {
        this.textSplitter = new RecursiveCharacterTextSplitter({
            chunkSize: 1000,
            chunkOverlap: 200,
            separators: ['\n\n', '\n', '. ', ' ', ''],
        });
    }

    /** Re-indexes a Supabase-stored document; replaces existing chunks, so it is safe to call repeatedly. */
    async indexStoredDocument(storagePath: string, itemUid: string): Promise<number> {
        return this.indexTemporaryFile(await this.supabaseService.downloadFile(storagePath), itemUid);
    }

    async indexRemoteDocument(fileUrl: string, itemUid: string): Promise<number> {
        return this.indexTemporaryFile(await this.downloadToTemporaryFile(fileUrl), itemUid);
    }

    /**
     * Documents generated by the tools service expose only a `fileUrl`, so accept
     * either source. Never throws: on failure `isEmbedded` is set to false so the
     * client can retry via PATCH.
     */
    async indexDocumentItem(item: { uid: string; type: LibraryItemType; metadata: LibraryItemMetadata | null }): Promise<boolean> {
        const metadata = item.metadata as Partial<DocumentMetadata> | null;
        const storagePath = metadata?.filePath;
        const fileUrl = metadata?.fileUrl;

        if (item.type !== 'DOCUMENT' || (!storagePath && !fileUrl)) {
            return false;
        }

        const db = this.databaseService.database;

        try {
            const chunks = storagePath
                ? await this.indexStoredDocument(storagePath, item.uid)
                : await this.indexRemoteDocument(fileUrl, item.uid);

            await db.update(libraryItem).set({ isEmbedded: true, updatedAt: new Date() }).where(eq(libraryItem.uid, item.uid));
            this.logger.log(`Indexed document ${item.uid} into ${chunks} chunks`);
            return true;
        } catch (error) {
            await db
                .update(libraryItem)
                .set({ isEmbedded: false, updatedAt: new Date() })
                .where(eq(libraryItem.uid, item.uid))
                .catch(() => undefined);

            this.logger.error(`Failed to index document ${item.uid}: ${error instanceof Error ? error.message : String(error)}`);
            return false;
        }
    }

    private async indexTemporaryFile(tempPath: string, itemUid: string): Promise<number> {
        try {
            return await this.indexPDF(tempPath, itemUid);
        } finally {
            if (fs.existsSync(tempPath)) fs.unlinkSync(tempPath);
        }
    }

    private async downloadToTemporaryFile(url: string): Promise<string> {
        const response = await firstValueFrom(this.httpService.get<ArrayBuffer>(url, { responseType: 'arraybuffer', timeout: 60_000 }));

        const tempPath = path.join(os.tmpdir(), `studymind_rag_${Date.now()}_${Math.random().toString(36).slice(2)}.pdf`);
        fs.writeFileSync(tempPath, Buffer.from(response.data));

        return tempPath;
    }

    /** Extracts, chunks and embeds a local PDF, replacing any existing chunks. */
    async indexPDF(filePath: string, itemUid: string): Promise<number> {
        const db = this.databaseService.database;

        const [item] = await db
            .select({ id: libraryItem.id, userId: libraryItem.userId })
            .from(libraryItem)
            .where(eq(libraryItem.uid, itemUid));

        if (!item) {
            throw new NotFoundException(`Library item not found for uid: ${itemUid}`);
        }

        const documents = await this.processPDF(filePath);
        if (!documents.length) {
            throw new BadRequestException('No extractable content found in pdf');
        }

        const splitDocs = await this.textSplitter.splitDocuments(documents);
        if (!splitDocs.length) {
            throw new BadRequestException('No chunks produced from pdf');
        }

        // Embed before deleting so a provider failure cannot destroy a working index.
        const embeddings = await this.embeddingService.embedDocuments(splitDocs.map(doc => doc.pageContent));

        const indexedAt = new Date().toISOString();
        const rows = splitDocs.map((doc, index) => ({
            itemId: item.id,
            userId: item.userId,
            chunkIndex: index,
            content: doc.pageContent,
            metadata: {
                source: (doc.metadata?.fileName as string) ?? path.basename(filePath),
                pageNumber: this.readPageNumber(doc.metadata),
                totalPages: (doc.metadata?.totalPages as number) ?? null,
                chunkIndex: index,
                totalChunks: splitDocs.length,
                contentLength: doc.pageContent.length,
                indexedAt,
            } satisfies DocumentChunkMetadata,
            embedding: embeddings[index],
        }));

        await db.transaction(async tx => {
            await tx.delete(documentChunk).where(eq(documentChunk.itemId, item.id));

            for (let i = 0; i < rows.length; i += INSERT_BATCH_SIZE) {
                await tx.insert(documentChunk).values(rows.slice(i, i + INSERT_BATCH_SIZE));
            }
        });

        this.logger.log(`Indexed ${rows.length} chunks for item ${itemUid}`);

        return rows.length;
    }

    async deleteByItemUids(itemUids: string[]): Promise<number> {
        if (!itemUids.length) return 0;

        const db = this.databaseService.database;

        const items = await db.select({ id: libraryItem.id }).from(libraryItem).where(inArray(libraryItem.uid, itemUids));
        if (!items.length) return 0;

        const deleted = await db
            .delete(documentChunk)
            .where(
                inArray(
                    documentChunk.itemId,
                    items.map(item => item.id),
                ),
            )
            .returning({ id: documentChunk.id });

        if (deleted.length) {
            this.logger.log(`Deleted ${deleted.length} chunks for ${itemUids.length} item(s)`);
        }

        return deleted.length;
    }

    async deleteByItemUid(itemUid: string): Promise<number> {
        return this.deleteByItemUids([itemUid]);
    }

    /** Returns a prompt-ready string, or '' when nothing matched. */
    async searchByItemUid(query: string, itemUid: string, userId: number, options: SearchOptions = {}): Promise<string> {
        const results = await this.search(query, userId, { ...options, itemUids: [itemUid] });

        if (!results.length) {
            return '';
        }

        return results
            .map(result => {
                const page = result.pageNumber ? `, page ${result.pageNumber}` : '';
                return `[Source: ${result.itemName}${page} | relevance ${result.score.toFixed(3)}]\n${result.content}`;
            })
            .join('\n\n---\n\n');
    }

    /** Ownership and active-state are enforced in SQL, not by the caller. */
    async search(query: string, userId: number, options: SearchOptions = {}): Promise<RetrievedChunk[]> {
        const limit = options.limit ?? this.configService.get<number>('retrieval.topK');
        const minScore = options.minScore ?? this.configService.get<number>('retrieval.minScore');

        const queryEmbedding = await this.embeddingService.embedQuery(query);
        const db = this.databaseService.database;

        const distance = cosineDistance(documentChunk.embedding, queryEmbedding);

        const conditions = [eq(documentChunk.userId, userId), eq(libraryItem.isActive, true)];
        if (options.itemUids?.length) {
            conditions.push(inArray(libraryItem.uid, options.itemUids));
        }

        const rows = await db
            .select({
                itemUid: libraryItem.uid,
                itemName: libraryItem.name,
                content: documentChunk.content,
                chunkIndex: documentChunk.chunkIndex,
                metadata: documentChunk.metadata,
                distance,
            })
            .from(documentChunk)
            .innerJoin(libraryItem, eq(documentChunk.itemId, libraryItem.id))
            .where(and(...conditions))
            .orderBy(distance)
            .limit(limit);

        return rows
            .map(row => ({
                itemUid: row.itemUid,
                itemName: row.itemName,
                content: row.content,
                chunkIndex: row.chunkIndex,
                pageNumber: row.metadata?.pageNumber ?? null,
                score: 1 - Number(row.distance),
            }))
            .filter(row => row.score >= minScore);
    }

    private async processPDF(filePath: string): Promise<Document[]> {
        if (!fs.existsSync(filePath)) {
            throw new BadRequestException(`PDF file not found: ${filePath}`);
        }

        const pdfLoader = new PDFLoader(filePath, { splitPages: true });

        let documents: Document[];
        try {
            documents = await pdfLoader.load();
        } catch (error) {
            throw new BadRequestException(`Failed to load pdf: ${error instanceof Error ? error.message : 'unknown error'}`);
        }

        const pages = documents.filter(doc => doc.pageContent.trim().length > 0);

        this.logger.log(`Loaded ${pages.length}/${documents.length} non-empty pages from ${path.basename(filePath)}`);

        return pages.map(doc => {
            doc.metadata = {
                ...doc.metadata,
                fileName: (doc.metadata?.fileName as string) ?? path.basename(filePath),
                totalPages: documents.length,
                contentLength: doc.pageContent.length,
            };
            return doc;
        });
    }

    /** Real page number from loader metadata; null rather than guessing, since blank pages are filtered out. */
    private readPageNumber(metadata: Document['metadata'] | undefined): number | null {
        const loc = metadata?.loc as { pageNumber?: number } | undefined;
        return typeof loc?.pageNumber === 'number' ? loc.pageNumber : null;
    }
}
